-- Partner-safe views (only approved columns)
-- ---------------------------------------------------------------------------
create or replace view public.partner_schedule_view with (security_invoker = true) as
select sc.id, sc.jour, sc.date, sc.heure_debut, sc.heure_fin, sc.salle,
       f.name as formation_name, m.titre as module_name,
       concat(t.prenom, ' ', t.nom) as teacher_name
from public.schedule sc
join public.formations f on f.id = sc.formation_id
join public.modules m on m.id = sc.module_id
join public.teachers t on t.id = sc.teacher_id;

create or replace view public.partner_test_view with (security_invoker = true) as
select t.id, t.titre, t.duree, t.niveau, t.date_debut, t.date_fin,
       m.titre as module_name, f.name as formation_name
from public.tests t
join public.modules m on m.id = t.module_id
join public.formations f on f.id = m.formation_id
where t.publie;

create or replace view public.partner_grade_view with (security_invoker = true) as
select g.id, g.student_id, g.note, g.appreciation, g.date,
       s.nom, s.prenom, m.titre as module_name, f.name as formation_name
from public.grades g
join public.students s on s.id = g.student_id
join public.modules m on m.id = g.module_id
join public.formations f on f.id = s.formation_id;

create or replace view public.partner_scholarship_view with (security_invoker = true) as
select sc.id, sc.student_id, sc.statut, sc.date, sc.date_attribution,
       s.nom, s.prenom, f.name as formation_name
from public.scholarships sc
join public.students s on s.id = sc.student_id
join public.formations f on f.id = s.formation_id;

create or replace view public.partner_module_view with (security_invoker = true) as
select m.id, m.numero, m.titre, m.icon, m.description, m.duree,
       f.id as formation_id, f.name as formation_name, f.code as formation_code
from public.modules m
join public.formations f on f.id = m.formation_id
where m.active
  and (public.is_admin() or public.partner_can_access_formation(m.formation_id));

create or replace view public.partner_report_view with (security_invoker = true) as
select
  (select count(*) from public.students)::integer as total_students,
  (select count(*) from public.teachers)::integer as total_teachers,
  (select count(*) from public.modules m where m.active and (public.is_admin() or public.partner_can_access_formation(m.formation_id)))::integer as active_modules,
  (select count(*) from public.attendance)::integer as total_attendance,
  (select count(*) from public.attendance where statut = 'present')::integer as total_present,
  (select count(*) from public.certificates)::integer as total_certificates;

revoke all on public.partner_student_view, public.partner_teacher_view,
  public.partner_course_view, public.partner_attendance_view,
  public.partner_certificate_view, public.partner_report_view,
  public.partner_schedule_view, public.partner_test_view,
  public.partner_grade_view, public.partner_scholarship_view from anon;
revoke all on public.partner_module_view from anon;
grant select on public.partner_student_view, public.partner_teacher_view,
  public.partner_course_view, public.partner_attendance_view,
  public.partner_certificate_view, public.partner_report_view,
  public.partner_schedule_view, public.partner_test_view,
  public.partner_grade_view, public.partner_scholarship_view to authenticated;
grant select on public.partner_module_view to authenticated;

-- ---------------------------------------------------------------------------
-- Client audit is constrained to a safe whitelist.
-- ---------------------------------------------------------------------------
drop policy if exists audit_logs_insert on public.audit_logs;
create or replace function public.record_client_audit(
  p_action text,
  p_entity_type text,
  p_entity_id text default null,
  p_description text default ''
) returns uuid
language plpgsql security definer set search_path = public
as $$
declare v_id uuid;
begin
  if auth.uid() is null then raise exception 'Authentication required'; end if;
  if p_action not in ('PARTNER_ACCESS','FILE_OPEN','FILE_DOWNLOAD','LOGOUT') then
    raise exception 'Audit action not allowed';
  end if;
  insert into public.audit_logs(user_id, action, entity_type, entity_id, description)
  values (auth.uid(), p_action, left(p_entity_type, 100), left(p_entity_id, 255), left(p_description, 1000))
  returning id into v_id;
  return v_id;
end;
$$;
grant execute on function public.record_client_audit(text,text,text,text) to authenticated;

