create or replace function public.partner_account_active()
returns boolean language sql stable security definer set search_path = public
as $$
  select coalesce(exists (
    select 1 from public.partner_users pu
    join public.profiles p on p.id = pu.user_id
    where pu.user_id = auth.uid()
      and p.role in ('partner','partner_admin')
      and p.active
      and pu.statut = 'actif'
      and pu.date_debut <= current_date
      and (pu.date_fin is null or pu.date_fin >= current_date)
  ), false);
$$;

create or replace function public.current_partner_scope()
returns text language sql stable security definer set search_path = public
as $$
  select pu.scope from public.partner_users pu
  where pu.user_id = auth.uid() and public.partner_account_active()
  limit 1;
$$;

create or replace function public.partner_has_scope(scopes text[])
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce(public.current_partner_scope() = any(scopes), false); $$;

create or replace function public.partner_can_access_formation(p_formation_id uuid)
returns boolean language sql stable security definer set search_path = public
as $$
  select coalesce(public.partner_account_active() and exists (
    select 1
    from public.partner_users pu
    join public.partner_organization_formations pof
      on pof.organization_id = pu.organization_id
    where pu.user_id = auth.uid() and pof.formation_id = p_formation_id
  ), false);
$$;

