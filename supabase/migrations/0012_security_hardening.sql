-- Production security hardening: profiles, RBAC overrides, partner scopes,
-- Storage isolation and client audit constraints.

-- ---------------------------------------------------------------------------
-- Profile privilege hardening
-- ---------------------------------------------------------------------------
drop policy if exists profiles_insert_own on public.profiles;
drop policy if exists profiles_update_own_or_admin on public.profiles;

create policy profiles_update_own_safe
on public.profiles for update to authenticated
using (id = auth.uid())
with check (id = auth.uid());

create policy profiles_admin_update
on public.profiles for update to authenticated
using (public.is_admin())
with check (public.is_admin());

-- RLS controls rows; column grants prevent users from changing role/status.
revoke insert, update, delete on public.profiles from authenticated;
grant select on public.profiles to authenticated;
grant update (name, phone, avatar_path) on public.profiles to authenticated;

-- ---------------------------------------------------------------------------
-- User-specific permission overrides
-- ---------------------------------------------------------------------------
create table if not exists public.user_permissions (
  user_id uuid not null references auth.users(id) on delete cascade,
  permission_code text not null references public.permissions(code) on delete cascade,
  allowed boolean not null default true,
  granted_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  primary key (user_id, permission_code)
);

alter table public.user_permissions enable row level security;
create policy user_permissions_self_read on public.user_permissions
for select to authenticated using (user_id = auth.uid() or public.is_admin());
create policy user_permissions_admin_all on public.user_permissions
for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy roles_superadmin_write on public.roles
for all to authenticated using (public.is_superadmin()) with check (public.is_superadmin());
create policy permissions_superadmin_write on public.permissions
for all to authenticated using (public.is_superadmin()) with check (public.is_superadmin());
create policy role_permissions_superadmin_write on public.role_permissions
for all to authenticated using (public.is_superadmin()) with check (public.is_superadmin());

create or replace function public.has_permission(permission_code text)
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce(
    (select up.allowed from public.user_permissions up
     where up.user_id = auth.uid() and up.permission_code = $1),
    exists (
      select 1 from public.role_permissions rp
      where rp.role_code = public.current_role()
        and rp.permission_code = $1
    ),
    false
  );
$$;

-- ---------------------------------------------------------------------------
-- Disable public self-signup at the database boundary.
-- Admin-created users carry app_metadata.provisioned_by; bootstrap carries
-- app_metadata.bootstrap. Public clients cannot write app_metadata.
-- ---------------------------------------------------------------------------
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
declare
  provisioner uuid;
  is_bootstrap boolean := coalesce((new.raw_app_meta_data ->> 'bootstrap')::boolean, false);
begin
  if is_bootstrap then
    perform pg_advisory_xact_lock(74202601);
    if exists (select 1 from public.profiles where role = 'superadmin' and active) then
      raise exception 'System already initialized';
    end if;
  else
    begin
      provisioner := nullif(new.raw_app_meta_data ->> 'provisioned_by', '')::uuid;
    exception when invalid_text_representation then
      provisioner := null;
    end;
    if provisioner is null or not exists (
      select 1 from public.profiles
      where id = provisioner and role in ('admin', 'superadmin') and active
    ) then
      raise exception 'Public signup is disabled';
    end if;
  end if;

  insert into public.profiles(id, username, name, email, role, active)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'username', split_part(new.email, '@', 1)),
    coalesce(new.raw_user_meta_data ->> 'name', split_part(new.email, '@', 1)),
    new.email,
    'student',
    true
  );
  return new;
end;
$$;

